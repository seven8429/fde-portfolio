import pandas as pd

data = {
    "经销商": ["杭州佰诚","北京光彩","广州兴盛","南京苏果","武汉中百",
             "成都红旗","郑州丹尼斯","西安爱家","沈阳中兴","福州永辉"],
    "区域":   ["华东","华北","华南","华东","华中",
             "华北","华中","西北","东北","华南"],
    "销量":   [3200,3600,4000,2800,1900,2600,2100,1500,1700,3300],
    "季度":   ["Q1","Q1","Q2","Q1","Q2","Q1","Q2","Q1","Q2","Q2"],
}
df = pd.DataFrame(data)

# 1) 选列：只要"经销商"和"销量"（对比 SELECT 经销商, 销量）
print("只选两列：")
print(df[["区域", "经销商", "销量"]])          # 注意：多列用双中括号

# 2) 按条件过滤：销量 > 3500（对比 WHERE 销量 > 3500）
print("\n销量 > 3500 的经销商：")
print(df[df["销量"] > 3500])

# 3) 组合条件：华南 且 销量 > 3000（用 &，每个条件加括号）
print("\n华南 且 销量 > 3000：")
print(df[(df["区域"] == "华南") & (df["销量"] > 3000)])

# 4) 过滤后再选指定列
print("\n华东经销商的名字和销量：")
print(df[df["区域"] == "华东"][["经销商", "销量"]])
